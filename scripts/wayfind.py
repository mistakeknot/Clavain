def ticket_type(issue: dict) -> str | None:
    found = [TYPE_LABELS[label] for label in issue.get("labels") or [] if label in TYPE_LABELS]
    return found[0] if len(found) == 1 else None


def type_labels(issue: dict) -> list[str]:
    return [label for label in issue.get("labels") or [] if label in TYPE_LABELS]


def map_kind(issue: dict) -> str | None:
    labels = issue.get("labels") or []
    found = [kind for kind, label in MAP_LABELS.items() if label in labels]
    return found[0] if len(found) == 1 else None


def normalize_project(name: str | None) -> str:
    """The project name a roadmap is scoped to: lower case, label-safe."""
    project = (name or "").strip().lower()
    if not PROJECT_NAME.fullmatch(project):
        raise WayfindError(f"invalid --project {name!r}: use 1-64 characters of a-z, 0-9, '.', '_' or '-', "
                           "starting with a letter or digit")
    return project


def project_names(issue: dict) -> list[str]:
    return [label[len(PROJECT_LABEL_PREFIX):] for label in issue.get("labels") or []
            if label.startswith(PROJECT_LABEL_PREFIX)]


def open_roadmaps(bd: Bd) -> list[dict]:
    return bd.json("list", "--label", ROADMAP_LABEL, "--limit", "0")


def horizon_of(issue: dict) -> str | None:
    found = [HORIZON_LABELS[label] for label in issue.get("labels") or [] if label in HORIZON_LABELS]
    return found[0] if len(found) == 1 else None


def load_map(bd: Bd, map_id: str) -> dict:
    issue = bd.show(map_id)
    if map_kind(issue) is None:
        raise WayfindError(f"{map_id} is not a map (no {MAP_LABEL} or {ROADMAP_LABEL} label)")
    return issue


def map_tickets(bd: Bd, map_id: str) -> list[dict]:
    return [c for c in bd.children(map_id) if c.get("id") != map_id]


def parse_time(value: str | None) -> dt.datetime | None:
    if not value:
        return None
    try:
        return dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None


