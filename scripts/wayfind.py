#!/usr/bin/env python3
"""Wayfind: a decision map kept in beads, for efforts whose route is not yet visible.

Adapted from the wayfinder skill in mattpocock/skills (MIT License,
Copyright (c) 2026 Matt Pocock). This file is the mechanism only: label and
body conventions plus four subcommands built from `bd`. The loop that uses it
is commands/wayfind.md.

A map is a beads epic labelled wayfinder:map. Each child is one decision
ticket carrying exactly one type label. The map body has four sections; the
Destination and Out of scope sections are the targets, and a hash of them is
stored in the body so `lint` can tell when they changed without a cited source.
Only `chart` writes the map body. Decisions live on the tickets: `resolve`
posts a resolution record as a comment on the ticket it closes, and `lint`
derives the map's decisions from those records.

While a HITL ticket is in flight, its claimant also holds the map epic itself
as a claim (the lease), so at most one HITL ticket per map is handed out.

    wayfind chart   create a map, add tickets to it, or retarget it
    wayfind ready   list the frontier, or claim one ticket from it
    wayfind resolve record a ticket's answer and close it
    wayfind lint    check the map's rules and report whether it converges
    wayfind render  write a roadmap map's committed bets to a generated markdown file
    wayfind adopt-roadmap  give a roadmap charted before project scoping its project label

A second map kind, a roadmap (label wayfinder:roadmap, one per project), reuses the
same tickets, lease, lint and --source rules for /clavain:waymap. Its tickets are
`bet`, research, task and revisit. A bet resolves to commit, defer or drop; a
committed bet carries a horizon label (waymap:now or waymap:next). The Later
horizon is the map's fog and is never charted. A roadmap never clears. Projects can
share one beads database, so a roadmap carries a project label (waymap:project:<name>,
set by `chart --project`) and the one-open-roadmap rule counts roadmaps per project.

Exit codes: 0 ok, 1 rule violation (the request is well formed but a map rule
refuses it, or lint found a broken rule), 2 usage, malformed spec or bd failure,
3 divergence alarm. A refused request changes nothing.
"""
