TARGET_SECTIONS = ("Destination", "Out of scope")
MAP_MARKER = "<!-- wayfind:map v1 -->"
TARGETS_RE = re.compile(r"<!-- wayfind:targets sha256=([0-9a-f]{64}) source=(.*?) -->")
RECORD_RE = re.compile(r"<!-- wayfind:resolution v1 (.*?) -->")
