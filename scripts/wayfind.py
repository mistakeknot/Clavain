PROJECT_NAME = re.compile(r"[a-z0-9][a-z0-9._-]{0,63}")
TYPES = ("grilling", "prototype", "research", "task", "revisit", "bet")
# Ticket types each map kind accepts. A bet exists only on a roadmap.
KIND_TYPES = {"map": ("grilling", "prototype", "research", "task", "revisit"),
              "roadmap": ("bet", "research", "task", "revisit")}
TYPE_LABELS = {f"wayfinder:{t}": t for t in TYPES}
# Tickets that resolve only on the owner's answer. A revisit reverses an owner decision, so it is one.
HITL_TYPES = frozenset({"grilling", "prototype", "revisit", "bet"})
DECISIONS = ("commit", "defer", "drop")
HORIZONS = ("now", "next")  # Later is fog, never a ticket
HORIZON_LABELS = {f"waymap:{h}": h for h in HORIZONS}
INVALIDATED_LABEL = "wayfinder:invalidated"
SUPERSEDED_LABEL = "wayfinder:superseded"

