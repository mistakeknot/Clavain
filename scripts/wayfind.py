def leaf_progress(bd: Bd, kids: list[dict], depth: int = 3) -> tuple[int, int]:
    """Return (closed, total) over the leaves under kids; an issue with children counts through them."""
    closed = total = 0
    for kid in kids:
        below = [c for c in bd.children(kid["id"]) if c.get("id") != kid["id"]] if depth > 1 else []
        if below:
            c, t = leaf_progress(bd, below, depth - 1)
        else:
            c, t = (1 if kid.get("status") == "closed" else 0), 1
        closed, total = closed + c, total + t
    return closed, total


def bet_work(bd: Bd, bet: dict) -> dict:
    """The work hanging under a committed bet: its direct children, and whether the bet is delivered.

    A bet is live while any direct child is open, and delivered once it has children and all are closed.
    """
    kids = [c for c in bd.children(bet["id"]) if c.get("id") != bet["id"]]
    closed, total = leaf_progress(bd, kids)
    open_kids = [k for k in kids if k.get("status") != "closed"]
    return {"children": [{"id": k["id"], "title": k.get("title", ""), "status": k.get("status", "")} for k in kids],
            "live": bool(open_kids), "delivered": bool(kids) and not open_kids,
            "closed": closed, "total": total}


def active_commitments(bd: Bd, map_id: str) -> list[dict]:
    """Committed Now + Next bets that are neither superseded nor delivered, read from labels."""
    return [t for t in map_tickets(bd, map_id)
            if t.get("status") == "closed" and ticket_type(t) == "bet" and horizon_of(t)
            and SUPERSEDED_LABEL not in (t.get("labels") or []) and not bet_work(bd, t)["delivered"]]


def pending_commitments(bd: Bd, map_id: str) -> list[dict]:
    """Bets whose commit record is written but whose horizon label is not yet: a resolve that stopped part way.

    They count against the cap, because the retry that finishes them will make them active.
    """
    out = []
    for t in map_tickets(bd, map_id):
        if ticket_type(t) != "bet" or horizon_of(t) or SUPERSEDED_LABEL in (t.get("labels") or []):
            continue
        records, _ = parse_records(bd.comments(t["id"]))
        if any(r.get("kind") == "resolved" and r.get("decision") == "commit" for r in records):
            out.append(t)
    return out


