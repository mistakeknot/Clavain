def evaluate(bd: Bd, map_id: str, cap: int, max_age_days: int, now: dt.datetime | None = None,
             bet_cap: int = DEFAULT_BET_CAP) -> dict:
    now = now or dt.datetime.now(dt.timezone.utc)
    issue = bd.show(map_id)
    errors: list[str] = []
    warnings: list[str] = []
    alarms: list[str] = []

    kind = map_kind(issue) or "map"
    if map_kind(issue) is None:
        errors.append(f"{map_id}: missing {MAP_LABEL} label")
    if MAP_LABEL in (issue.get("labels") or []) and ROADMAP_LABEL in (issue.get("labels") or []):
        errors.append(f"{map_id}: carries both {MAP_LABEL} and {ROADMAP_LABEL}; it is one kind of map")
    body = issue.get("description") or ""
    sections = parse_body(body)
    for name in SECTIONS:
        if name not in sections:
            errors.append(f"{map_id}: missing section '## {name}'")
    marker = targets_marker(body)
    if marker is None:
        errors.append(f"{map_id}: no targets marker; Destination has no recorded source")
    elif marker[0] != targets_digest(sections):
        errors.append(f"{map_id}: Destination or Out of scope changed without a cited source "
                      "(use wayfind chart --map ... --source ...)")

    tickets = map_tickets(bd, map_id)
    by_id = {t["id"]: t for t in tickets}
    open_tickets = [t for t in tickets if t.get("status") != "closed"]
    closed = [t for t in tickets if t.get("status") == "closed"]
    invalidated = [t for t in closed if INVALIDATED_LABEL in (t.get("labels") or [])]
    resolved = [t for t in closed if t not in invalidated]
    in_flight = [t for t in open_tickets if t.get("status") == "in_progress" and ticket_type(t) in HITL_TYPES]
    holder = (issue.get("assignee") or None) if issue.get("status") == "in_progress" else None

    for t in tickets:
        labels = type_labels(t)
        if len(labels) != 1:
            errors.append(f"{t['id']}: needs exactly one type label, has {labels or 'none'}")
        for map_label in MAP_LABELS.values():
            if map_label in (t.get("labels") or []):
                warnings.append(f"{t['id']}: carries {map_label}; only the map should")
        if len(labels) == 1 and ticket_type(t) not in KIND_TYPES[kind]:
            errors.append(f"{t['id']}: a {kind} takes only {', '.join(KIND_TYPES[kind])} tickets, "
                          f"not {ticket_type(t)}")

    # A resolve that stopped part way leaves its record on a still-open ticket.
    for t in open_tickets:
        records, malformed = parse_records(bd.comments(t["id"]))
        if malformed:
            errors.append(f"{t['id']}: malformed wayfind resolution record")
        if any(r != records[0] for r in records[1:]):
            errors.append(f"{t['id']}: conflicting resolution records on an open ticket (two sessions "
                          "recorded different answers); wayfind cannot resolve it, so ask the owner which stands")

    # Decisions come from the resolution records on the closed tickets.
    record_of: dict[str, dict] = {}
    superseders: dict[str, list[str]] = {}
    committed_horizon: dict[str, str] = {}
    for t in closed:
        records, malformed = parse_records(bd.comments(t["id"]))
        if malformed:
            errors.append(f"{t['id']}: malformed wayfind resolution record")
        if not records:
            errors.append(f"{t['id']}: closed without a wayfind resolution record; reopen it (bd reopen) "
                          f"and resolve it with wayfind resolve")
            continue
        if any(r != records[0] for r in records[1:]):
            errors.append(f"{t['id']}: conflicting resolution records; settle it with the owner "
                          "and record the change with a revisit ticket")
            continue
        rec = records[0]
        record_of[t["id"]] = rec
        if (rec["kind"] == "invalidated") != (t in invalidated):
            errors.append(f"{t['id']}: resolution record says {rec['kind']} but the {INVALIDATED_LABEL} label "
                          "disagrees; rerun its wayfind resolve with the same arguments")
        if rec["kind"] != "resolved":
            continue
        if ticket_type(t) in HITL_TYPES and not rec.get("source"):
            errors.append(f"{t['id']}: {ticket_type(t)} ticket resolved without the owner's answer as its source")
        if ticket_type(t) == "bet":
            if rec.get("decision") not in DECISIONS:
                errors.append(f"{t['id']}: bet resolved without a commit, defer or drop decision")
            elif rec["decision"] == "commit":
                if rec.get("horizon") in HORIZONS:
                    committed_horizon[t["id"]] = rec["horizon"]
                else:
                    errors.append(f"{t['id']}: bet committed without a Now or Next horizon")
        if ticket_type(t) == "revisit":
            target = rec.get("supersedes") or ""
            if not target:
                errors.append(f"{t['id']}: revisit resolved without superseding a decision")
                continue
            superseders.setdefault(target, []).append(t["id"])
            if SUPERSEDED_LABEL not in (by_id.get(target, {}).get("labels") or []):
                errors.append(f"{t['id']}: supersedes {target}, which is not labelled {SUPERSEDED_LABEL}; "
                              f"rerun wayfind resolve {t['id']} with the same arguments")
    for t in tickets:
        named = superseders.get(t["id"], [])
        if SUPERSEDED_LABEL in (t.get("labels") or []) and len(named) != 1:
            errors.append(f"{t['id']}: labelled superseded but named by {len(named)} resolved revisit tickets, "
                          "not exactly one")
        elif len(named) > 1:
            errors.append(f"{t['id']}: superseded by more than one revisit ({', '.join(named)})")
    # A horizon label is the committed bet's, and only the committed bet's: it must match its record.
    for t in tickets:
        have = sorted(label for label in t.get("labels") or [] if label in HORIZON_LABELS)
        want = [f"waymap:{committed_horizon[t['id']]}"] if t["id"] in committed_horizon else []
        if have != want:
            errors.append(f"{t['id']}: horizon label {have or 'none'} disagrees with its resolution record "
                          f"({want or 'not a committed bet'}); rerun its wayfind resolve with the same arguments")
    decisions = []
    for t in resolved:
        rec = record_of.get(t["id"], {})
        if rec.get("kind") != "resolved":
            continue
        entry = {"id": t["id"], "title": t.get("title", ""), "summary": rec.get("summary", ""),
                 "source": rec.get("source", ""), "superseded_by": (superseders.get(t["id"]) or [None])[0]}
        if ticket_type(t) == "bet":
            entry.update({"decision": rec.get("decision"), "horizon": rec.get("horizon") or None})
        decisions.append(entry)

    roadmap = None
    if kind == "roadmap":
        owners = project_names(issue)
        if not owners:
            warnings.append(f"{map_id}: roadmap has no project label, so it counts against no project; "
                            f"adopt it with wayfind adopt-roadmap {map_id} --project NAME")
        elif len(owners) > 1:
            errors.append(f"{map_id}: carries {len(owners)} project labels ({', '.join(owners)}); a roadmap "
                          "belongs to one project")
        else:
            twins = [r["id"] for r in open_roadmaps(bd) if r["id"] != map_id and owners[0] in project_names(r)]
            if twins and issue.get("status") != "closed":
                errors.append(f"{map_id}: project {owners[0]} has more than one open roadmap "
                              f"({map_id}, {', '.join(twins)}); close the extra one")
        bets = []
        for t in resolved:
            if t["id"] in committed_horizon and not superseders.get(t["id"]):
                bets.append({"id": t["id"], "title": t.get("title", ""), "horizon": committed_horizon[t["id"]],
                             "summary": record_of[t["id"]].get("summary", ""), **bet_work(bd, t)})
        active = [b for b in bets if not b["delivered"]]
        if len(active) > bet_cap:
            errors.append(f"{len(active)} committed Now + Next bets, above the cap of {bet_cap}; "
                          "defer or drop some with a revisit ticket")
        now_bets = [b for b in active if b["horizon"] == "now"]
        if not now_bets:
            warnings.append("Now has no live child: no committed Now bet; commit one, or the roadmap is stale")
        for b in now_bets:
            if not b["live"]:
                warnings.append(f"{b['id']}: Now has no live child here; open this bet's work (a wayfind map "
                                "or a strategy epic) as a child of the bet")
        roadmap = {"bet_cap": bet_cap, "active": len(active),
                   "now": [b for b in active if b["horizon"] == "now"],
                   "next": [b for b in active if b["horizon"] == "next"],
                   "delivered": [b for b in bets if b["delivered"]]}

    if len(in_flight) > 1:
        errors.append(f"{len(in_flight)} HITL tickets in flight ({', '.join(t['id'] for t in in_flight)}); "
                      "run them one at a time")
    if holder and not in_flight:
        warnings.append(f"{map_id}: leased to {holder} with no HITL ticket in flight; if that session is gone, "
                        f'free it with bd update {map_id} --status open --assignee ""')
    for t in in_flight:
        if t.get("assignee") != holder:
            warnings.append(f"{t['id']}: HITL ticket in flight without the map lease "
                            f"(lease held by {holder or 'nobody'}); claim HITL tickets with wayfind ready --claim")
    if len(open_tickets) > cap:
        warnings.append(f"{len(open_tickets)} open tickets, above the cap of {cap}; return the far ones to fog")

    fog_text = sections.get("Not yet specified", "")
    fog = 0 if is_placeholder(fog_text) else len(bullets(fog_text))
    created = parse_time(issue.get("created_at"))
    closed_times = [ts for ts in (parse_time(t.get("closed_at")) for t in closed) if ts is not None]
    last_closed = max(closed_times, default=None)
    last_activity = last_closed or created
    age_days = (now - created).days if created else None
    idle_days = (now - last_activity).days if last_activity else None

    # Divergence alarms only. Routine progress is never reported.
    if len(invalidated) >= 2 and len(invalidated) > len(resolved):
        alarms.append(f"diverging: {len(invalidated)} tickets invalidated against {len(resolved)} resolved; "
                      "the route keeps changing under the map, so revisit the Destination with the owner")
    if open_tickets and idle_days is not None and idle_days >= max_age_days:
        alarms.append(f"stale: no ticket resolved for {idle_days} days with {len(open_tickets)} open")

    cleared = kind == "map" and not open_tickets and fog == 0 and bool(resolved) and not errors
    report = {
        "map": map_id,
        "fog": fog,
        "open": len(open_tickets),
        "resolved": len(resolved),
        "invalidated": len(invalidated),
        "invalidated_ratio": round(len(invalidated) / len(resolved), 2) if resolved else None,
        "age_days": age_days,
        "idle_days": idle_days,
        "hitl_in_flight": [t["id"] for t in in_flight],
        "lease": holder,
        "decisions": decisions,
        "cleared": cleared,
        "errors": errors,
        "warnings": warnings,
        "alarms": alarms,
    }
    if roadmap is not None:
        report["kind"] = "roadmap"
        report["roadmap"] = roadmap
    return report


def cmd_lint(bd: Bd, args) -> int:
    report = evaluate(bd, args.map, args.cap, args.max_age_days, bet_cap=args.bet_cap)
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        ratio = report["invalidated_ratio"]
        print(f"wayfind {report['map']}: fog={report['fog']} open={report['open']} resolved={report['resolved']} "
              f"invalidated={report['invalidated']} ratio={'-' if ratio is None else ratio} "
              f"age={report['age_days']}d idle={report['idle_days']}d"
              + (f" now={len(report['roadmap']['now'])} next={len(report['roadmap']['next'])}"
                 if "roadmap" in report else ""))
        for kind in ("errors", "warnings", "alarms"):
            for line in report[kind]:
                print(f"{kind[:-1].upper()}: {line}")
        if report["cleared"]:
            print("cleared: no open tickets and no fog; hand the map to /clavain:strategy")
    if report["errors"]:
        return EXIT_RULE
    if report["alarms"]:
        return EXIT_ALARM
    return EXIT_OK


