class Bd:
    """Thin wrapper over the bd CLI. Every write goes through bd itself."""

    def __init__(self, binary: str | None = None, directory: str | None = None, actor: str | None = None):
        self.binary = binary or os.environ.get("WAYFIND_BD", "bd")
        self.directory = directory
        self.actor = actor
        self.workspace: str | None = None  # the beads workspace identity, read once (see workspace_root)

    def run(self, *args: str, stdin: str | None = None) -> str:
        cmd = [self.binary]
        if self.directory:
            cmd += ["-C", self.directory]
        if self.actor:
            cmd += ["--actor", self.actor]
        cmd += list(args)
        try:
            proc = subprocess.run(cmd, input=stdin, capture_output=True, text=True, timeout=120)
        except FileNotFoundError as exc:
            raise WayfindError(f"bd not found: {self.binary}") from exc
        except subprocess.TimeoutExpired as exc:
            raise WayfindError(f"bd {' '.join(args[:2])} timed out") from exc
        if proc.returncode != 0:
            detail = (proc.stderr or proc.stdout).strip().splitlines()
            raise WayfindError(f"bd {' '.join(args[:2])} failed: {detail[-1] if detail else proc.returncode}")
        return proc.stdout

    def json(self, *args: str):
        out = self.run(*args, "--json")
        try:
            return json.loads(out) if out.strip() else []
        except json.JSONDecodeError as exc:
            raise WayfindError(f"bd {' '.join(args[:2])} returned non-JSON output") from exc

    def show(self, issue_id: str) -> dict:
        data = self.json("show", issue_id)
        if isinstance(data, list):
            if not data:
                raise WayfindError(f"{issue_id}: not found")
            data = data[0]
        return data

    def children(self, map_id: str) -> list[dict]:
        return self.json("list", "--parent", map_id, "--all", "--limit", "0")

    def ready_ids(self, map_id: str) -> list[str]:
        return [i["id"] for i in self.json("ready", "--parent", map_id, "--unassigned", "--limit", "0")]

    def create(self, title: str, description: str, labels: list[str], *, parent: str | None = None,
               issue_type: str = "task", blocked_by: list[str] | None = None) -> str:
        """Create one issue, labels and blocking links included, in a single bd call."""
        args = ["create", "--title", title, "-t", issue_type, "--body-file", "-"]
        if labels:
            args += ["-l", ",".join(labels)]
        if parent:
            # bd copies the parent's labels onto children; a ticket must not look like a map.
            args += ["--parent", parent, "--no-inherit-labels"]
        if blocked_by:
            # A bare id makes the new issue blocked by it ("blocks:<id>" means the reverse).
            args += ["--deps", ",".join(blocked_by)]
        out = self.run(*args, "--json", stdin=description)
        try:
            return json.loads(out)["id"]
        except (json.JSONDecodeError, KeyError) as exc:
            raise WayfindError("bd create returned no id") from exc

    def set_description(self, issue_id: str, body: str) -> None:
        self.run("update", issue_id, "--body-file", "-", stdin=body)

    def add_label(self, issue_id: str, label: str) -> None:
        self.run("update", issue_id, "--add-label", label)

    def remove_label(self, issue_id: str, label: str) -> None:
        self.run("update", issue_id, "--remove-label", label)

    def comments(self, issue_id: str) -> list[dict]:
        return self.json("comments", issue_id) or []

    def comment(self, issue_id: str, text: str) -> None:
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False) as fh:
            fh.write(text)
            path = fh.name
        try:
            self.run("comments", "add", issue_id, "-f", path)
        finally:
            os.unlink(path)

    def close(self, issue_id: str, reason: str) -> None:
        self.run("close", issue_id, "--reason", reason)

    def claim(self, issue_id: str) -> None:
        self.run("update", issue_id, "--claim")

    def release(self, issue_id: str) -> None:
        self.run("update", issue_id, "--status", "open", "--assignee", "")

    def whoami(self) -> str:
        """The name bd records as assignee on --claim: --actor, $BEADS_ACTOR, git user.name, $USER."""
        if self.actor:
            return self.actor
        if os.environ.get("BEADS_ACTOR"):
            return os.environ["BEADS_ACTOR"]
        cmd = ["git"] + (["-C", self.directory] if self.directory else []) + ["config", "user.name"]
        try:
            name = subprocess.run(cmd, capture_output=True, text=True, timeout=10).stdout.strip()
        except (OSError, subprocess.TimeoutExpired):
            name = ""
        return name or os.environ.get("USER", "")


def current_uid() -> int:
    return os.getuid()


def lock_dir() -> Path:
    """The one private directory for lock files, the same for every process of this user.

    It is fixed by the account's home directory, not by XDG_RUNTIME_DIR, XDG_STATE_HOME or HOME:
    a process that sees different variables must still take the same lock for the same map, or
    two writers would each hold a lock and still race. WAYFIND_LOCK_DIR overrides it for tests
    and sandboxes; every writer of one workspace has to share that value.
    """
    override = os.environ.get("WAYFIND_LOCK_DIR")
    if override:
        if not os.path.isabs(override):
            raise WayfindError(f"WAYFIND_LOCK_DIR must be an absolute path, not {override!r}: a relative "
                               "one names a different directory from each working directory, so writers "
                               "would stop excluding each other")
        return Path(override)
    try:
        home = pwd.getpwuid(current_uid()).pw_dir
    except (KeyError, AttributeError):
        home = ""
    if not home or not os.path.isabs(home):
        raise WayfindError("cannot find an absolute home directory for the wayfind lock files "
                           f"(the account database says {home!r}); set WAYFIND_LOCK_DIR to an absolute "
                           "private directory you own")
    return Path(home) / ".local" / "state" / "clavain-wayfind"


def workspace_root(bd: Bd) -> str:
    """The beads workspace's own identity, the same from every working directory and -C spelling."""
    if bd.workspace:  # read once, so a map creation cannot find it unreadable after its epic exists
        return bd.workspace
    try:
        where = json.loads(bd.run("where", "--json")).get("path")
    except (WayfindError, json.JSONDecodeError, AttributeError) as exc:
        raise WayfindError("cannot tell which beads workspace this is (bd where --json failed: "
                           f"{exc}); refusing to write to a map without its lock, so fix bd and rerun") from None
    if not isinstance(where, str) or not os.path.isabs(where):
        raise WayfindError("cannot tell which beads workspace this is (bd where --json gave no absolute "
                           "path); refusing to write to a map without its lock, so fix bd and rerun")
    bd.workspace = os.path.realpath(where)
    return bd.workspace


def lock_path(bd: Bd, scope: str) -> Path:
    """A lock file name for the beads workspace and the map, inside the private lock directory."""
    digest = hashlib.sha256(f"{workspace_root(bd)}\0{scope}".encode("utf-8")).hexdigest()[:24]
    return lock_dir() / f"{digest}.lock"


def open_lock(path: Path) -> int:
    """Open the lock file, trusting nothing about what is already on disk.

    The directory must be a real directory (never a symlink) owned by this user with mode 0700, and
    the file a regular file owned by this user that no one else can write. Otherwise another user
    could plant or swap the entry and defeat the lock, so the command fails instead of running
    without it.
    """
    directory = path.parent
    try:
        directory.parent.mkdir(parents=True, exist_ok=True)
        try:
            os.mkdir(directory, 0o700)
            os.chmod(directory, 0o700)  # a umask can only have removed bits; we made this one
        except FileExistsError:
            pass
        dir_fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    except OSError as exc:
        raise WayfindError(f"lock directory {directory} is not usable ({exc.strerror or exc}); "
                           "remove it or fix it, then rerun") from None
    try:
        info = os.fstat(dir_fd)
        if info.st_uid != current_uid() or stat.S_IMODE(info.st_mode) != 0o700:
            raise WayfindError(f"lock directory {directory} must be owned by you with mode 0700; "
                               "fix or remove it, then rerun")
        try:
            fd = os.open(path.name, os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600, dir_fd=dir_fd)
        except OSError as exc:
            raise WayfindError(f"lock file {path} cannot be opened ({exc.strerror or exc}); "
                               "remove it, then rerun") from None
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_uid != current_uid() or info.st_mode & 0o022:
            os.close(fd)
            raise WayfindError(f"lock file {path} must be a regular file owned by you that no one else can "
                               "write; remove it, then rerun")
        return fd
    finally:
        os.close(dir_fd)


@contextlib.contextmanager
def map_lock(bd: Bd, scope: str):
    """Hold an exclusive lock on one map while a command checks a rule and writes under it.

    bd has no transactions, so a rule such as the bet cap holds only if the count and the write
    happen under one lock. The lock covers wayfind writers of one beads workspace on one host;
    a bd write made outside wayfind is not serialized. A lock file left by a crashed run is
    harmless: the lock is the flock, which the system drops with the process, not the file.
    """
    if fcntl is None:
        raise WayfindError("this platform has no file locks, so wayfind cannot serialize writes to a map")
    timeout = float(os.environ.get("WAYFIND_LOCK_TIMEOUT") or LOCK_TIMEOUT)
    fd = open_lock(lock_path(bd, scope))
    try:
        deadline = time.monotonic() + timeout
        while True:
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except OSError:
                if time.monotonic() >= deadline:
                    raise WayfindError(f"another wayfind command has held the lock on {scope} for {timeout:g}s; "
                                       "wait for it and rerun") from None
                time.sleep(0.1)
        yield
    finally:
        os.close(fd)  # closing drops the flock; the empty file stays in the private directory


