def read_text(value: str | None, path: str | None) -> str | None:
    if path:
        return Path(path).read_text(encoding="utf-8")
    return value


SPEC_KEYS = frozenset({"tickets", "fog", "graduate", "notes"})
TICKET_KEYS = frozenset({"key", "type", "title", "question", "blocked_by"})


def _strings(value, what: str) -> list[str]:
    if value is None:
        return []
    if not isinstance(value, list) or not all(isinstance(v, str) and v.strip() for v in value):
        raise WayfindError(f"{what} must be a list of non-empty strings")
    return [v.strip() for v in value]


def load_spec(path: str | None) -> dict:
    """Read and shape-check a ticket spec. Nothing is written until the whole spec passes."""
    if not path:
        return {"tickets": [], "fog": [], "graduate": [], "notes": ""}
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if isinstance(data, list):
        data = {"tickets": data}
    if not isinstance(data, dict):
        raise WayfindError("ticket spec must be a JSON object or list")
    unknown = sorted(set(data) - SPEC_KEYS)
    if unknown:
        raise WayfindError(f"ticket spec: unknown key(s) {', '.join(unknown)}")
    raw = data.get("tickets") or []
    if not isinstance(raw, list):
        raise WayfindError("ticket spec: tickets must be a list")
    tickets, keys = [], set()
    for i, ticket in enumerate(raw):
        if not isinstance(ticket, dict):
            raise WayfindError(f"ticket {i}: must be an object")
        unknown = sorted(set(ticket) - TICKET_KEYS)
        if unknown:
            raise WayfindError(f"ticket {i}: unknown key(s) {', '.join(unknown)}")
        if ticket.get("type") not in TYPES:
            raise WayfindError(f"ticket {i}: type must be one of {', '.join(TYPES)}")
        for field in ("title", "question"):
            if field in ticket and not isinstance(ticket[field], str):
                raise WayfindError(f"ticket {i}: {field} must be a string")
        if not (ticket.get("title") or "").strip():
            raise WayfindError(f"ticket {i}: title is required")
        key = ticket.get("key", i)
        if not isinstance(key, (str, int)) or isinstance(key, bool) or not str(key).strip():
            raise WayfindError(f"ticket {i}: key must be a non-empty string or an integer")
        key = str(key).strip()
        if key in keys:
            raise WayfindError(f"ticket {i}: duplicate key {key!r}")
        keys.add(key)
        blocked = ticket.get("blocked_by")
        if isinstance(blocked, list):
            # Integer blockers name the index keys of earlier tickets.
            blocked = [str(b) if isinstance(b, int) and not isinstance(b, bool) else b for b in blocked]
        tickets.append({**ticket, "key": key, "blocked_by": _strings(blocked, f"ticket {i}: blocked_by")})
    notes = data.get("notes") or ""
    if not isinstance(notes, str):
        raise WayfindError("ticket spec: notes must be a string")
    return {"tickets": tickets, "fog": _strings(data.get("fog"), "fog"),
            "graduate": _strings(data.get("graduate"), "graduate"), "notes": notes}


def creation_order(tickets: list[dict], existing_ids: set[str]) -> list[dict]:
    """Order new tickets so each one's blockers exist before it. Refuses unknown blockers and cycles.

    A blocked_by entry names a spec key or an existing ticket of this map.
    """
    keys = {t["key"] for t in tickets}
    for t in tickets:
        if t["key"] in existing_ids:
            raise WayfindError(f"ticket key {t['key']!r} is also an existing ticket id; rename the key")
        for blocker in t["blocked_by"]:
            if blocker not in keys and blocker not in existing_ids:
                raise WayfindError(f"ticket {t['key']!r}: blocker {blocker!r} is neither a spec key "
                                   "nor a ticket of this map")
    ordered, placed = [], set()
    pending = list(tickets)
    while pending:
        ready = [t for t in pending if all(b in placed or b not in keys for b in t["blocked_by"])]
        if not ready:
            raise WayfindError("blocked_by forms a cycle among: " + ", ".join(t["key"] for t in pending))
        for t in ready:
            ordered.append(t)
            placed.add(t["key"])
        pending = [t for t in pending if t["key"] not in placed]
    return ordered


def check_kind_types(tickets: list[dict], kind: str) -> None:
    for t in tickets:
        if t["type"] not in KIND_TYPES[kind]:
            raise RuleError(f"ticket {t['key']!r}: a {kind} takes only {', '.join(KIND_TYPES[kind])} tickets, "
                            f"not {t['type']}")


def ticket_body(ticket: dict, map_id: str) -> str:
    parts = [f"Map: {map_id}", f"Type: {ticket['type']}", ""]
    parts.append((ticket.get("question") or ticket["title"]).strip())
    if ticket.get("type") in HITL_TYPES:
        parts += ["", "Resolves only on the owner's answer: a live reply while the owner is present, "
                      "or a card pick. An agent's choice is a recommendation, never the resolution."]
    if ticket.get("type") == "revisit":
        parts += ["Resolve it with --supersedes naming the closed decision it replaces."]
    if ticket.get("type") == "bet":
        parts += ["Resolve it with --decision commit (and --horizon now or next), defer or drop, "
                  "and --source naming who decided. Open the bet's work as children of this ticket."]
    return "\n".join(parts) + "\n"


def apply_edits(sections: dict[str, str], spec: dict, destination: str | None,
                out_of_scope: str | None) -> list[str]:
    """Apply one chart run's body edits to sections in place; return the resulting fog."""
    if destination is not None:
        sections["Destination"] = destination.strip()
    if out_of_scope is not None:
        sections["Out of scope"] = out_of_scope.strip()
    fog = [] if is_placeholder(sections.get("Not yet specified", "")) else bullets(sections["Not yet specified"])
    for item in spec["graduate"]:
        if item not in fog:
            raise WayfindError(f"cannot graduate {item!r}: not in Not yet specified")
        fog.remove(item)
    fog += [item for item in spec["fog"] if item not in fog]
    sections["Not yet specified"] = set_bullets(fog)
    if spec["notes"].strip():
        notes = "" if is_placeholder(sections.get("Notes", "")) else sections["Notes"]
        sections["Notes"] = (notes + "\n" + spec["notes"].strip()).strip()
    return fog


def write_map_body(bd: Bd, map_id: str, base: dict[str, str], marker: tuple[str, str] | None, spec: dict,
                   destination: str | None, out_of_scope: str | None, source: str,
                   created: dict[str, str]) -> list[str]:
    """Rebase this run's edits onto the body as it is now, write it, and read it back.

    bd has no compare-and-set, so a write that races another chart run in the window
    between the re-read and the write is detected by the read-back, not prevented.
    """
    done = ", ".join(f"{k}={v}" for k, v in created.items()) or "none"
    fresh_body = bd.show(map_id).get("description") or ""
    fresh = parse_body(fresh_body)
    if targets_marker(fresh_body) != marker or targets_digest(fresh) != targets_digest(base):
        raise WayfindError(f"map {map_id} was retargeted while this chart ran; created {done}; the map body "
                           "was not written. Rerun with only the fog, graduate and notes edits")
    sections = dict(fresh)
    try:
        fog = apply_edits(sections, spec, destination, out_of_scope)
    except WayfindError as exc:
        raise WayfindError(f"{exc} (the map body changed while this chart ran); created {done}; "
                           "the map body was not written") from exc
    body = render_body(sections, source)
    bd.set_description(map_id, body)
    written = bd.show(map_id).get("description") or ""
    if parse_body(written) != parse_body(body) or targets_marker(written) != targets_marker(body):
        raise WayfindError(f"map {map_id}: another write landed on the body at the same time; created {done}. "
                           "Run wayfind lint, then rerun the fog, graduate and notes edits that are missing")
    return fog


def cmd_chart(bd: Bd, args) -> int:
    if args.dry_run:
        return _chart(bd, args)
    # The open-ticket cap, the one-roadmap rule and the body rebase all read before they write.
    # bd accepts a map under several spellings (wm-abc, abc); the lock is keyed on the ID bd
    # resolves them to, the same one resolve and map creation lock, so every spelling shares it.
    if args.map:
        shown = bd.show(args.map)
        canonical = shown.get("id") if isinstance(shown, dict) else None
        if not isinstance(canonical, str) or not canonical:
            raise WayfindError(f"bd did not report an ID for {args.map}; refusing to chart without it "
                               "(an existing-map request never becomes a new map)")
        args.map = canonical
    with map_lock(bd, args.map or "new-map"):
        return _chart(bd, args)


def check_project_free(bd: Bd, project: str | None) -> None:
    """Refuse a second open roadmap for one project; warn about roadmaps that have no project yet.

    The rule is per project because projects can share one beads database. A roadmap charted
    before project scoping has no project label, so it cannot say whose it is: it blocks no one,
    and the warning points at `adopt-roadmap`."""
    if project is None:
        raise WayfindError("a new roadmap needs --project NAME: projects can share one beads database, so the "
                           "one-open-roadmap rule is counted per project (for example --project aleph)")
    roadmaps = open_roadmaps(bd)
    same = [r["id"] for r in roadmaps if project in project_names(r)]
    if same:
        raise RuleError(f"project {project} already has an open roadmap ({', '.join(same)}); work it with "
                        "/clavain:waymap, or close it before charting another")
    legacy = [r["id"] for r in roadmaps if not project_names(r)]
    if legacy:
        print(f"wayfind: warning: open roadmap(s) without a project label: {', '.join(legacy)}. If one is "
              f"{project}'s, adopt it instead (wayfind adopt-roadmap MAP_ID --project {project})", file=sys.stderr)


def create_tickets(bd: Bd, map_id: str, tickets: list[dict]) -> dict[str, str]:
    # Tickets first, each created whole (labels and blockers in one bd call), the map body last.
    # A failure part way leaves the body as it was, so graduated fog is never lost and the map
    # cannot read as cleared while tickets are missing.
    created: dict[str, str] = {}
    try:
        for ticket in tickets:
            blockers = [created[b] if b in created else b for b in ticket["blocked_by"]]
            created[ticket["key"]] = bd.create(ticket["title"], ticket_body(ticket, map_id),
                                               [f"wayfinder:{ticket['type']}"], parent=map_id,
                                               blocked_by=blockers)
    except WayfindError as exc:
        done = ", ".join(f"{k}={v}" for k, v in created.items()) or "none"
        raise WayfindError(f"{exc}. Map {map_id}: created {done}; the map body is unchanged. Rerun with "
                           "only the tickets not yet created, keeping fog and graduate as they were") from exc
    return created


def _chart(bd: Bd, args) -> int:
    # Every check runs before the first write, so a refused or malformed request changes nothing.
    spec = load_spec(args.tickets)
    destination = read_text(args.destination, args.destination_file)
    out_of_scope = read_text(args.out_of_scope, args.out_of_scope_file)
    retarget = destination is not None or out_of_scope is not None
    project = normalize_project(args.project) if args.project is not None else None
    if project is not None and (args.map or (args.kind or "map") != "roadmap"):
        raise WayfindError("--project scopes a new roadmap; it is not accepted with --map or for a plain map "
                           "(adopt an existing roadmap with `wayfind adopt-roadmap`)")

    if args.map:
        issue = load_map(bd, args.map)
        kind = map_kind(issue)
        if args.kind and args.kind != kind:
            raise RuleError(f"{args.map} is a {kind}, not a {args.kind}")
        map_id = args.map
        body = issue.get("description") or ""
        base = parse_body(body)
        marker = targets_marker(body)
        source = marker[1] if marker else ""
        if not retarget:
            check_targets(map_id, body, base)
        if retarget:
            if not args.source:
                raise RuleError("changing Destination or Out of scope needs --source (the owner's card pick or a ruling)")
            source = args.source
        existing = map_tickets(bd, map_id)
    else:
        if not args.title or destination is None:
            raise WayfindError("a new map needs --title and --destination (or --destination-file)")
        if not args.source:
            raise RuleError("a new map needs --source: where the owner set the Destination")
        kind = args.kind or "map"
        if kind == "roadmap":
            check_project_free(bd, project)
        base = {"Destination": "", "Out of scope": "", "Notes": "", "Not yet specified": ""}
        marker = None
        source = args.source
        map_id = None
        existing = []
    sections = dict(base)
    fog = apply_edits(sections, spec, destination, out_of_scope)
    check_kind_types(spec["tickets"], kind)
    if kind == "roadmap" and destination is not None and len(destination.strip().splitlines()) != 1:
        raise RuleError("a roadmap's Destination is one horizon sentence on one line")

    tickets = creation_order(spec["tickets"], {t["id"] for t in existing})
    open_now = [t for t in existing if t.get("status") != "closed"]
    if len(open_now) + len(tickets) > args.cap and not args.allow_over_cap:
        raise RuleError(
            f"{len(open_now)} open + {len(tickets)} new tickets exceeds the cap of {args.cap}; "
            "keep the rest as fog, or pass --allow-over-cap")

    if args.dry_run:
        print(json.dumps({"map": map_id, "kind": kind, "project": project, "create_map": map_id is None, "retarget": retarget and bool(map_id),
                          "tickets": [{"key": t["key"], "type": t["type"], "title": t["title"],
                                       "blocked_by": t["blocked_by"]} for t in tickets],
                          "fog": fog}, indent=2))
        return EXIT_OK

    if map_id is None:
        labels = [MAP_LABELS[kind]] + ([PROJECT_LABEL_PREFIX + project] if kind == "roadmap" else [])
        map_id = bd.create(f"[{kind}] {args.title}", render_body(sections, source), labels, issue_type="epic")
        # The new map is visible to /chart --map from here on, and those writers hold the lock on its
        # ID, not on "new-map". Take that lock too and recount under it before adding tickets.
        with map_lock(bd, map_id):
            open_now = [t for t in map_tickets(bd, map_id) if t.get("status") != "closed"]
            if len(open_now) + len(tickets) > args.cap and not args.allow_over_cap:
                raise RuleError(
                    f"map {map_id} was created, but another chart added tickets to it first: {len(open_now)} open + "
                    f"{len(tickets)} new exceeds the cap of {args.cap}. Chart the rest with --map {map_id}, "
                    "or keep it as fog")
            created = create_tickets(bd, map_id, tickets)
    else:
        created = create_tickets(bd, map_id, tickets)

    if args.map:
        fog = write_map_body(bd, map_id, base, marker, spec, destination, out_of_scope, source, created)
        if retarget:
            bd.comment(map_id, f"Targets changed. Source: {source}")

    print(json.dumps({"map": map_id, "tickets": created, "fog": len(fog)}) if args.json
          else f"map {map_id}: {len(created)} ticket(s) created, {len(fog)} fog item(s)")
    return EXIT_OK


